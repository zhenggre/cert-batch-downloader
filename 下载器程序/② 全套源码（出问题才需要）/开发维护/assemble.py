# ---- 安全写文件：编不了的字符自动替换，绝不留空文件 ----
# 踩过的坑：文档里放了 ⚠ ✓ 这类字符，write_text 抛异常后
# 磁盘上留下一个 0 字节的说明书。同事打开一片空白，还得回来问——
# 而这份说明书正是他"联系不上人时唯一能指望的东西"，不能出这种哑巴事故。
#
# 为什么是 utf-8-sig（UTF-8 带 BOM）而不是 GBK / 纯 UTF-8：
#   GBK      → Windows 记事本能显示（靠系统 ANSI 代码页猜对），
#              但预览面板、VSCode、浏览器、微信里打开一律乱码。
#              实测踩过一次：自己看没问题，别人看全是方块。
#   纯 UTF-8 → 现代工具正确，但记事本在中文系统上会按 GBK 猜，同样乱码。
#   utf-8-sig → 记事本认 BOM、Excel 认 BOM、现代工具也认 BOM，两头都对。
# 这是唯一"在哪儿打开都正常"的选择，别再改回 GBK。
FALLBACK = {"✓": "※", "⚠": "※", "★": "※", "✅": "OK", "❌": "X",
            "→": "->", "—": "-", "·": "·", "•": "·"}


def write_doc(path, text, encoding="utf-8-sig", min_size=500):
    try:
        path.write_text(text, encoding=encoding, newline="\r\n")
    except UnicodeEncodeError:
        bad = set()
        clean = []
        for ch in text:
            try:
                ch.encode(encoding)
                clean.append(ch)
            except UnicodeEncodeError:
                bad.add(ch)
                clean.append(FALLBACK.get(ch, "□"))
        path.write_text("".join(clean), encoding=encoding, newline="\r\n")
        print("  注意：说明书里有字符无法用 %s 编码，已自动替换：%s"
              % (encoding, " ".join(sorted(bad))))
    size = path.stat().st_size
    if size < min_size:
        raise RuntimeError("文档写入异常：%s 只有 %d 字节（应至少 %d）"
                           % (path.name, size, min_size))
    return size


