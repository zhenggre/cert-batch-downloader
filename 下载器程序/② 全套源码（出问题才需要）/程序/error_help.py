def resume_steps(reason="blocked", done=0, total=0):
    """给出「现在该怎么办」的完整步骤。reason 用实际故障类型，别写死。"""
    L = [_RULE]
    L.append("【任务提前停止】这不是白干")
    if total:
        L.append("  本次已处理 %d / %d 人" % (done, total))
    L.append("  成绩和已下载的证书都保存在本地，重新运行会自动跳过，不会重复劳动。")
    L.append("")
    if reason == "proxy":
        L.append("  现在请按顺序做这 2 步（几分钟就能继续）：")
        L.append("    第 1 步｜退出 VPN / 加速器；或到「设置 → 网络和 Internet → 代理」，"
                 "关掉「使用代理服务器」。")
        L.append("    第 2 步｜重新双击程序、选同一份名单、同一个输出目录，点「开始」。")
        L.append("            程序会自动跳过已完成的，只补还没做的部分。")
        L.append("")
        L.append("  如果公司网络强制走代理、而这个网站又访问不了，改用手机热点即可绕开。")
        L.append("  换成热点后立刻正常 → 说明问题在代理，不必去打扰主办方。")
    elif reason == "blocked":
        L.append("  现在请按顺序做这 3 步（约 10 分钟就能继续）：")
        L.append("    第 1 步｜等 30 分钟。这段时间什么都别点，让网站那边把限制解开。")
        L.append("    第 2 步｜换网络。手机打开「个人热点」，电脑连上这个热点。")
        L.append("    第 3 步｜重新双击程序、选同一份名单、同一个输出目录，点「开始」。")
        L.append("            程序会自动跳过已完成的，只补还没做的部分。")
        L.append("")
        L.append("  如果换了网络还是很快被拦：说明网站封得比较紧，改在晚上或早上人少时跑；")
        L.append("  也可以自己把速度调慢：用记事本打开程序文件夹里的 config.json，")
        L.append("  把「每条间隔秒数」改大一点（比如 1.6 改成 3.0），存盘后重启程序即可 ——")
        L.append("  或者让技术支持帮你调。")
        L.append("  千万不要连续反复重试——越试，网站把限制时间放得越长。")
    elif reason == "dns":
        L.append("  现在请这样做：")
        L.append("    第 1 步｜用浏览器手动打开一次比赛网址，确认网站还开着。")
        L.append("    第 2 步｜检查网络（随便开个常用网站试试），必要时换手机热点。")
        L.append("    第 3 步｜恢复后重新运行程序，会自动跳过已完成的。")
    else:
        L.append("  请检查网络是否正常，然后重新运行即可（已完成的会自动跳过）。")
    L.append(_RULE)
    return L


