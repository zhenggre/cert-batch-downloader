# 作业结束后的总结建议
# ------------------------------------------------------------------
def finish_advice(kinds, stats, aborted=False):
    """kinds: 本次出现过的故障类型集合；stats: 最终状态计数。
    返回逐行文本；没有值得说的事情时返回空列表。"""
    L = []
    hits = [k for k in ("blocked", "dns", "timeout", "server", "net", "proxy") if k in kinds]
    download_issues = [k for k in ("pdf_stuck", "pdf_weird") if k in kinds]

    n_fail_q = stats.get("查询失败", 0)
    n_fail_d = stats.get("下载失败", 0)

    if not hits and not download_issues and not n_fail_q and not n_fail_d:
        return L

    L.append("")
    L.append("=" * 64)
    L.append("本次运行遇到的问题 & 处理建议")
    L.append("=" * 64)

    if aborted:
        rk = "proxy" if "proxy" in kinds else ("blocked" if "blocked" in kinds else "dns")
        L.extend(resume_steps(rk, stats.get("_done", 0), stats.get("_total", 0)))
    elif "blocked" in kinds:
        L.append("⚠ 本次出现过「被网站限流」的迹象。")
        L.append("   如果还有很多人没查完：等 30 分钟 → 换手机热点 → 重新运行（会自动跳过已完成的）。")
        L.append("")

    if n_fail_q:
        L.append("· 查询失败 %d 人：这些人没拿到结果。" % n_fail_q)
        L.append("  处理：隔 30 分钟重新运行一次即可，程序只补失败的部分。")
        L.append("")
    if n_fail_d:
        L.append("· 证书下载失败 %d 份：名单里这些人是获奖的，但证书文件没取到。" % n_fail_d)
        L.append("  处理：重新运行一次通常就好；个别一直失败的，请手动去网站下载。")
        L.append("")

    if download_issues:
        L.append("· 证书文件在网站那边没生成出来（这是网站的问题，不是程序的问题）。")
        L.append("  处理：重新运行即可，成功过的会自动跳过。")
        L.append("")

    if "dns" in kinds:
        L.append("· 出现过连不上网站的情况。")
        L.append("  处理：先用浏览器打开一次查询网址确认；打不开就换网络，或联系主办方。")
        L.append("")

    if "server" in kinds:
        L.append("· 比赛网站服务器本次出过故障（5xx）。这通常是对方的问题。")
        L.append("  处理：换个时间段再跑。如果报的是 503，参考下面「被限流」的处理方式。")
        L.append("")

    if "proxy" in kinds:
        L.append("· 请求曾被本机/公司代理拦下（这是网络设置问题，不是比赛网站的问题）。")
        L.append("  处理：退出 VPN / 加速器，或到「设置 → 网络和 Internet → 代理」关掉代理；")
        L.append("        最省事的是用手机开热点给电脑连，再跑一次。")
        L.append("")

    L.append("-" * 64)
    L.append("详细日志和故障说明见输出目录里的「故障诊断_日期.txt」——")
    L.append("它跟下载好的证书放在同一个文件夹里，界面上也能点「打开报告」直接开。")
    L.append("需要求助时，把那一份发给技术支持就行；不用发这份界面日志，")
    L.append("也不用另外写一段话描述。")
    L.append("=" * 64)
    return L


def headline(kinds, stats):
    """把"这次到底出了什么事"压成一行，摆在报告最顶上。

    为什么一定要有这个：同事转发时只会说"它跑出错了"，我打开文件得先
    翻到第三部分读完日志才知道出没出大事。先把结论写脸上，双方都省一轮。
    """
    if not stats:
        return "程序在开始查询之前就中断了（原因见第二部分）。"
    n_q = stats.get("查询失败", 0) or 0
    n_d = stats.get("下载失败", 0) or 0
    n_ok = (stats.get("成功", 0) or 0) + (stats.get("已完成跳过", 0) or 0)
    if not n_q and not n_d:
        return "没有失败记录，但有异常情况被记了下来（见第二部分），供排查用。"
    bits = []
    if n_ok:
        bits.append("成功 %d 人" % n_ok)
    if n_q:
        bits.append("查询失败 %d 人" % n_q)
    if n_d:
        bits.append("下载失败 %d 份" % n_d)
    return "%s —— 共 %d 处没成功，原因与处理办法见第二部分。" % ("，".join(bits), n_q + n_d)


def env_info(version="", site=None, site_key="", proxy="", extra=None):
    """收集「只有排查才用得上」的运行环境信息。

    同事看不懂这些，所以单独摆在报告末尾；但对接手的人很关键：
    「跑的是哪一版」「是不是打包版」「系统里的 Python 什么版本」「走没走代理」，
    这几条能省掉三四轮来回追问。站点标识和字段映射则用来判断
    「是不是这个比赛的配置本身就不对」。
    """
    import platform
    import sys
    d = {}
    if version:
        d["程序版本"] = version
    d["运行方式"] = "打包版（exe）" if getattr(sys, "frozen", False) else "源码运行"
    d["Python"] = platform.python_version()
    d["操作系统"] = platform.platform()
    d["本机代理"] = proxy or "未检测到"
    if site:
        if site_key:
            d["站点标识"] = site_key
        if site.get("title"):
            d["站点名称"] = site["title"]
        if site.get("query_url"):
            d["查询接口"] = site["query_url"]
        fm = site.get("field_map") or {}
        if fm:
            d["字段映射"] = ", ".join("%s=%s" % (k, fm[k]) for k in sorted(fm))
    if extra:
        for k, v in extra.items():
            d[k] = v
    return d


def write_report(path, kinds, stats, detail_lines, meta=None,
                 tech=None, names=None):
    """把本次遇到的故障与建议落盘，方便同事转发求助。

    这份文件的读者有两个，而且顺序不能反：
      ① 出问题的同事 —— 只看"第二部分：怎么办"（人话，照着做就行）；
      ② 被求助的人（技术支持 / 开发）—— 先看顶上的现场信息，再看日志和技术信息。
    所以顶部必须把「什么时间、哪个网址、哪份名单、干了什么」一次写全：
    同事转发时不用再补一段说明，接手的人也不用反过来问 —— 一问一答又是半天。
    """
    from datetime import datetime
    L = []
    L.append("比赛证书下载器 · 故障诊断报告")
    L.append("=" * 64)
    L.append("生成时间：%s" % datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    if meta:
        for k, v in meta.items():
            L.append("%s：%s" % (k, v))
    L.append("")
    L.append("出了什么问题：%s" % headline(kinds, stats))
    L.append("=" * 64)
    L.append("  这份文件怎么用：直接发给技术支持即可，")
    L.append("  不用另外写一段话描述 —— 该说的它都写清楚了。")
    L.append("  （学生姓名已自动打码、证件号和手机号已隐去，")
    L.append("   本机用户名也不会带出去，可以直接转发。）")
    L.append("=" * 64)
    L.append("")
    L.append("-" * 64)
    L.append("一、本次统计")
    L.append("-" * 64)
    if not stats:
        L.append("  （还没开始查询就中断了，没有统计数字）")
    for k, v in stats.items():
        if str(k).startswith("_"):
            continue
        L.append("  %-12s %s" % (k, v))
    L.append("")
    L.append("-" * 64)
    L.append("二、出现过的故障与处理方法")
    L.append("-" * 64)
    if not kinds:
        L.append("  本次没有出现可归类的故障。")
        L.append("  若仍有失败记录，多半是网站那边的偶发问题：重新跑一次即可，")
        L.append("  已经成功过的会自动跳过，不会白干。")
    else:
        for k in kinds:
            L.extend(explain(k, tag="本次出现"))
            L.append("")
    L.append("-" * 64)
    L.append("三、完整日志（每行带时间，便于对时间线）")
    L.append("-" * 64)
    L.extend(detail_lines or [])
    if tech:
        L.append("")
        L.append("-" * 64)
        L.append("四、运行环境信息（给排查的人看，同事可以直接跳过）")
        L.append("-" * 64)
        for k, v in tech.items():
            L.append("  %s：%s" % (k, v))
    try:
        # utf-8-sig：这份报告要转发给别人看（技术支持、同事），
        # 带 BOM 才能保证记事本和各种编辑器里打开都不乱码
        #
        # scrub 放在最后、一次作用在整份文本上：这样以后谁往 L 里加了什么
        # （多一条日志、多一段建议），都不会漏掉脱敏。
        body = scrub("\n".join(L), names=names)
        with open(path, "w", encoding="utf-8-sig") as f:
            f.write(body)
        return str(path)
    except Exception:
        return ""
