import re


# ======================================================================
# 脱敏 —— 这份报告是要往外发的
# ======================================================================
# 背景（2026-09-22 复盘）：
#   报告里原本逐条打印「姓名 | 学校 | 奖项」，而顶部写着「原样发给技术支持
#   就行，不用挑、不用删」。597 人的名单跑下来，这份文件里就是几百个未成年人
#   的姓名加学校 —— 而程序正在主动教用户把它转发出去。
#   现在改成：姓名只留姓、证件号和手机号整体隐去、本机用户名换成占位符。
#
# 学校名保留不脱敏：一所学校动辄上百人，单独出现不构成个人识别，
# 而「哪个学校的数据有问题」恰恰是排查时最有用的一条线索。
_ID_RE = re.compile(
    r"(?<!\d)[1-9]\d{5}(?:19|20)\d{2}(?:0[1-9]|1[0-2])"
    r"(?:0[1-9]|[12]\d|3[01])\d{3}[\dXx](?!\d)")
_PHONE_RE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")
# 只处理「盘符 + Users 段 + 用户名」这种本机用户目录路径。
# 其它盘符路径（譬如 D 盘下的桌面目录）不含个人信息，留着对排查有用，
# 不动它。
_HOME_RE = re.compile(r"[A-Za-z]:\\+Users\\+[^\\\s\"',;)]+", re.I)


def mask_name(name):
    """姓名脱敏：只留姓，其余打星。

    单字名（比如「雷」）整个打星 —— 留一个姓等于把名字说出去了。
    """
    n = (name or "").strip()
    if not n:
        return n
    if len(n) == 1:
        return "*"
    return n[0] + "*" * (len(n) - 1)


def scrub(text, names=()):
    """把报告文本里的个人信息处理掉，返回处理后的文本。

    姓名按「先长后短」替换：名单里同时有「张伟」和「张伟明」时先替换长的，
    否则短名会先把长名的前半截吃掉，最后留下一个「**明」。
    """
    if not text:
        return text
    out = str(text)
    for n in sorted({str(x).strip() for x in names if x and str(x).strip()},
                    key=len, reverse=True):
        if n in out:
            out = out.replace(n, mask_name(n))
    out = _HOME_RE.sub("%USERPROFILE%", out)
    out = _ID_RE.sub("<证件号已隐去>", out)
    out = _PHONE_RE.sub("<手机号已隐去>", out)
    return out


